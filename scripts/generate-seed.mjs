// Generates supabase/seed.sql (22 subjects × 30 placeholder sets) from src/lib/catalog.ts.
// Usage: node scripts/generate-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const src = readFileSync(path.join(root, "src/lib/catalog.ts"), "utf8");
const siteSrc = readFileSync(path.join(root, "src/lib/site.ts"), "utf8");
const setPaise = Number(/setPaise:\s*(\d+)/.exec(siteSrc)[1]);
const bundlePaise = Number(/subjectBundlePaise:\s*(\d+)/.exec(siteSrc)[1]);
const sets = Number(/SETS_PER_SUBJECT\s*=\s*(\d+)/.exec(siteSrc)[1]);

const re = /s\("(10|12)",\s*"([^"]+)",\s*"([^"]+)",\s*"(\d+)",\s*"([^"]+)"/g;
const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const lines = [
  "-- Generated by scripts/generate-seed.mjs — placeholders for every subject and set.",
  "-- Safe to re-run: existing rows (and your prices / publish flags) are kept.",
  "",
];
let m, order = 0;
const ids = [];
while ((m = re.exec(src))) {
  const [, cls, slug, name, code, stream] = m;
  const id = `class-${cls}-${slug}`;
  ids.push(id);
  lines.push(
    `insert into public.subjects (id, class_level, slug, name, code, stream, sort_order, bundle_price_paise) values (${q(id)}, ${q(cls)}, ${q(slug)}, ${q(name)}, ${q(code)}, ${q(stream)}, ${order++}, ${bundlePaise}) on conflict (id) do update set name = excluded.name, code = excluded.code, stream = excluded.stream, sort_order = excluded.sort_order;`,
  );
}
lines.push("");
lines.push(
  `insert into public.papers (subject_id, set_no, title, price_paise)\nselect s.id, n, 'Paper ' || n || ' · Set ' || n, ${setPaise}\nfrom public.subjects s cross join generate_series(1, ${sets}) as n\non conflict (subject_id, set_no) do nothing;`,
);
lines.push("");
writeFileSync(path.join(root, "supabase/seed.sql"), lines.join("\n"));
console.log(`seed.sql written: ${ids.length} subjects × ${sets} sets`);
